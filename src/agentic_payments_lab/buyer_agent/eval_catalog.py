"""Bounded metadata for existing offline coverage; never selects or executes code."""

import json
from pathlib import Path
from typing import Annotated, Literal, get_args

from pydantic import BaseModel, ConfigDict, Field, model_validator

MAX_CATALOG_BYTES = 32_768
MAX_RECORD_BYTES = 4_096
ERROR_MESSAGE = "Offline evaluation catalog is invalid or unavailable."

CaseId = Literal[
    "new_unknown",
    "replay_unknown",
    "operator_delivered",
    "incident_visible",
    "wire_paid",
    "wire_replay",
    "wire_missing_usage",
]
Suite = Literal["offline_x402", "responses_mock_over_simulator"]
X402Check = Literal[
    "completed_host_run",
    "original_identity",
    "financial_report_binding",
    "authoritative_phase",
    "authoritative_exposure",
    "one_double_execution",
    "one_bound_synthetic_transfer",
    "single_accounting_transition",
    "delivery_truth",
    "incident_visible",
    "operator_required",
    "fixture_labels",
    "actual_tool_trace",
    "durable_report",
]
WireCheck = Literal[
    "host_termination",
    "host_completion",
    "authoritative_report_fields",
    "persisted_run_correspondence",
    "authoritative_simulator_state",
    "one_authority_charge",
    "receipt_correspondence",
    "actual_tool_trace",
    "actual_dispatch_accounting",
    "complete_wire_bound",
    "usage_and_reservation",
]

# Symbolic metadata only. None of these strings is an import, path or callable reference.
_CASES = {
    "offline_x402": ("new_unknown", "replay_unknown", "operator_delivered", "incident_visible"),
    "responses_mock_over_simulator": ("wire_paid", "wire_replay", "wire_missing_usage"),
}
_GROUPS = {
    "offline_x402": ("x402_lifecycle", "scripted_x402_asgi_doubles"),
    "responses_mock_over_simulator": (
        "simulator_wire_lifecycle",
        "scripted_responses_mock_simulator",
    ),
}
_LAYOUT = tuple(
    (case_id, suite, _GROUPS[suite][0], order, _GROUPS[suite][1])
    for suite, ids in _CASES.items()
    for order, case_id in enumerate(ids, start=1)
)
_CHECKS = {
    "offline_x402": frozenset(get_args(X402Check)),
    "responses_mock_over_simulator": frozenset(get_args(WireCheck)),
}


class CatalogError(ValueError):
    """Fixed public error; rejected records and source exceptions are not echoed."""


class CaseV1(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True, frozen=True)

    version: Annotated[int, Field(strict=True, ge=1, le=1)]
    case_id: CaseId
    suite: Suite
    sequence_group: Literal["x402_lifecycle", "simulator_wire_lifecycle"]
    sequence_order: Annotated[int, Field(strict=True, ge=1, le=4)]
    description: Annotated[str, Field(min_length=1, max_length=200, pattern=r"^[^\x00-\x1f\x7f]+$")]
    fixture: Literal["scripted_x402_asgi_doubles", "scripted_responses_mock_simulator"]
    expected_checks: Annotated[
        tuple[X402Check | WireCheck, ...],
        Field(min_length=1, max_length=14, json_schema_extra={"uniqueItems": True}),
    ]

    @model_validator(mode="after")
    def existing_case_binding(self):
        binding = (self.case_id, self.suite, self.sequence_group, self.sequence_order, self.fixture)
        if binding not in _LAYOUT:
            raise ValueError("case binding")
        if self.description != self.description.strip() or not self.description.strip():
            raise ValueError("description")
        if (
            len(set(self.expected_checks)) != len(self.expected_checks)
            or frozenset(self.expected_checks) != _CHECKS[self.suite]
        ):
            raise ValueError("check identifiers")
        return self


def case_json_schema() -> dict:
    """Generate record structure; Python additionally enforces catalog semantics."""
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "urn:agentic-payments-lab:eval-case:v1",
        "$comment": (
            "Generated by eval_catalog.case_json_schema; see evals/README.md for semantics."
        ),
        **CaseV1.model_json_schema(),
    }


def _unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate JSON field")
        result[key] = value
    return result


def _no_constant(_):
    raise ValueError("nonfinite JSON number")


def decode_catalog(data: bytes) -> tuple[CaseV1, ...]:
    """Validate one UTF-8 JSON object per line, in the two existing linked sequences."""
    try:
        if type(data) is not bytes or len(data) > MAX_CATALOG_BYTES:
            raise ValueError("catalog size or type")
        lines = data.split(b"\n")
        if lines[-1] == b"":
            lines.pop()
        if len(lines) != len(_LAYOUT):
            raise ValueError("case count")
        cases = []
        for line in lines:
            if not line.strip() or len(line) > MAX_RECORD_BYTES:
                raise ValueError("record size")
            text = line.decode("utf-8")
            # Check duplicate keys/nonfinite constants before Pydantic parses the same JSON.
            # Its strict JSON path maps arrays to immutable tuples, without scalar coercion.
            json.loads(text, object_pairs_hook=_unique_object, parse_constant=_no_constant)
            cases.append(CaseV1.model_validate_json(text))
        if tuple(case.case_id for case in cases) != tuple(row[0] for row in _LAYOUT):
            raise ValueError("case identity or sequence")
        return tuple(cases)
    except (ValueError, TypeError, RecursionError):
        raise CatalogError(ERROR_MESSAGE) from None


def load_catalog(path: Path) -> tuple[CaseV1, ...]:
    """Read only the caller-supplied catalog path, with one bounded read. No execution."""
    try:
        with Path(path).open("rb") as handle:
            return decode_catalog(handle.read(MAX_CATALOG_BYTES + 1))
    except (OSError, TypeError, ValueError):
        raise CatalogError(ERROR_MESSAGE) from None
